"""The UI Protocol: what a Session needs from whoever shows a plugin's messages."""

from __future__ import annotations

from typing import Protocol


class UI(Protocol):
    """What a Session needs from whoever shows a plugin's messages and asks its questions (PlainUI).

    Session.cancel() does not interrupt a handler blocked on user input (prompt_user, form): the host waits in that
    handler. A UI that is embedded in another host must unblock its own input when it cancels (and may then return
    {"eof": True}).
    """

    def begin(self) -> None: ...

    def end(self) -> None: ...

    def output(self, p: dict) -> None: ...

    def log(self, p: dict) -> None: ...

    def bar(self, p: dict) -> None: ...

    def table(self, p: dict) -> None: ...

    def panel(self, p: dict) -> None: ...

    def clear(self, p: dict) -> None: ...

    def prompt_user(self, p: dict) -> dict: ...

    def form(self, p: dict) -> dict: ...

    def warn(self, message: str) -> None: ...

    def handlers(self) -> dict: ...
